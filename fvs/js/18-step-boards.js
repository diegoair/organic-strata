let symbolPaletteIn = null;   // the Palette the Symbol came in with this visit
// "Palette · Symbol’s own" only while it is: changed on the Symbol step (now, or on an earlier visit)
function syncSymbolPaletteHint() {
  const own = state.activeTier === 'symbol' && ((state.symbolPalette && state.symbolPalette.own) || (symbolPaletteIn != null && paletteKey(livePaletteWithGround()) !== symbolPaletteIn));
  ctrl('palette-symbol-hint').hidden = !own;
}
function symbolPaletteSwap(from, to) {
  if (from === to || (from !== 'symbol' && to !== 'symbol')) return;
  if (to === 'symbol') {
    if (typeof elementSaveNow === 'function') elementSaveNow();   // the Element's Palette goes back on it first
    const own = state.symbolPalette && state.symbolPalette.own;
    const p = own ? state.symbolPalette : { ...livePaletteWithGround(), own: false };   // not changed here yet: the Element's, as it is now
    symbolPaletteIn = paletteKey(p);
    applyPalette(p);
    showGroundControls(p.ground || null);
  } else {
    const now = livePaletteWithGround(), was = state.symbolPalette;
    state.symbolPalette = { ...now, own: !!(was && was.own) || paletteKey(now) !== symbolPaletteIn };
    const e = state.elements.find(x => x.id === state.activeElement);
    applyPalette(e && e.palette);
    showGroundControls(e && e.app ? e.app.ground || null : null);
  }
  onAppearanceChange();
}
function withPalette(p, fn) {
  p = p || DEFAULT_PALETTE;
  const prev = { colors: state.colors, colorRule: state.colorRule, paperColor: state.paperColor };
  state.colors = p.colors.map(hexKey); state.colorRule = { ...DEFAULT_COLOR_RULE, ...(p.colorRule || {}) }; state.paperColor = p.paperColor;
  try { return fn(); } finally { Object.assign(state, prev); }
}

// ── The Element list: the user's work, in their account (Organica.store, signed out = this browser's cache) ────────
// One row per Element ({name, custom, seed, app, n = its place}) + the row 'board' ({active}).
export const ELEMENTS = Organica.store('fvs-elements');
const BOARD_ROW = 'board';
const LEGACY_ITEMS = 'organica.fvs.proto.board.element.items';   // the prototype's list (Oct 2026) — read forward once, left in place
function readElements() {
  const obj = ELEMENTS.read() || {};
  // an Element without a shape (left by a half-done add) is dropped, never allowed to stop the whole board
  let items = Object.entries(obj).filter(([k, v]) => k !== BOARD_ROW && v && v.seed && v.seed.type)
    .map(([id, v]) => ({ id, name: v.name, custom: !!v.custom, seed: v.seed, app: v.app, ...(v.palette ? { palette: v.palette } : {}), ...(v.gallery ? { gallery: v.gallery } : {}), ...(v.galPos ? { galPos: v.galPos } : {}), n: v.n || 0 })).sort((a, b) => a.n - b.n);
  let active = obj[BOARD_ROW] && obj[BOARD_ROW].active;
  if (!items.length) {
    try { const s = JSON.parse(localStorage.getItem(LEGACY_ITEMS)); if (s && s.items) { items = s.items.filter(e => e && e.id && e.seed && e.seed.type).map(e => ({ id: e.id, name: e.name, custom: !!e.custom, seed: e.seed, app: e.app })); active = s.active; } } catch (err) {}
  }
  items.forEach(e => { delete e.n; });
  return { items, active };
}
function writeElements() {
  const obj = {};
  state.elements.forEach((e, i) => { obj[e.id] = { name: e.name, custom: !!e.custom, seed: e.seed, app: e.app, ...(e.palette ? { palette: e.palette } : {}), ...(e.gallery ? { gallery: e.gallery } : {}), ...(e.galPos ? { galPos: e.galPos } : {}), n: i }; });
  obj[BOARD_ROW] = { active: state.activeElement };
  try { ELEMENTS.write(obj); } catch (err) {}
}

