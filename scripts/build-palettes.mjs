// Builds TuneSutra's palette library (the Supabase `palettes` table) from the Hue × tone lab's data.
//
//   node scripts/build-palettes.mjs <lab book-pages dir> <out dir>
//
// The lab data (explorations/tunesutra-hue-tone/book-pages/*.js) is local and gitignored, and so is the output:
// neither ever goes into git. The output is rows.json (one object per palette, with its facets) and seed.sql
// for the table (applied by the owner — the table has no write policy).
//
// Rows, in this order (position):
//   pair    — two colours, from a key-colour page
//   triad   — three colours, from a key-colour page (some named by an image word)
//   bsa     — base · secondary · accent, three or four colours (the role pages)
//   five    — five colours in a space (background · ground · main · sub · accent)
//   gen     — six and seven colours, generated by the role rule from each key colour (Organica's own set)
// Colours are stored in TuneSutra's role order (shared/hue-tone.js ROLE_PARTS[n]), with that `parts` list.
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [labDir, outDir] = process.argv.slice(2);
if (!labDir || !outDir) { console.error('usage: node scripts/build-palettes.mjs <lab book-pages dir> <out dir>'); process.exit(2); }

// ---- the model (same loader as scripts/test-hue-tone.mjs) ----
const coreSrc = fs.readFileSync(path.join(root, 'shared/core.js'), 'utf8');
const grab = name => {
  const m = coreSrc.match(new RegExp('Organica\\.' + name + ' = function[\\s\\S]*?\\n  };'));
  if (!m) throw new Error('core.js: Organica.' + name + ' not found');
  return m[0];
};
const ctx = vm.createContext({ Math, String, parseInt, Number, Object, Array, Map, Set, Error, Organica: {} });
ctx.globalThis = ctx;
vm.runInContext(['normalizeHex', 'hexToRGB255', 'rgbToHex'].map(grab).join('\n'), ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'shared/color.js'), 'utf8'), ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'shared/hue-tone.js'), 'utf8'), ctx);
const HT = ctx.Organica.hueTone;

// ---- the lab data ----
const data = vm.createContext({ window: {} });
['book-data.js', 'garment-data.js', 'scene-data.js'].forEach(f => vm.runInContext(fs.readFileSync(path.join(labDir, f), 'utf8'), data));
const BD = data.window.BOOK_DATA.pages, GD = data.window.GARMENT_DATA.pages, SD = data.window.SCENE_DATA.pages;

const cap = w => w ? w.charAt(0).toUpperCase() + w.slice(1) : '';
const okTok = t => typeof t === 'string' && (/^\d+-\d+-\d+$/.test(t) || /^#[0-9a-f]{6}$/i.test(t) || !!HT.METAL[t]);
const toneRelKey = r => ({ 'same tone': 'same', 'near tones': 'near', 'far tones': 'far' })[r] || 'none';
const purityKey = p => ({ 'all clear': 'clear', 'all dull': 'dull', 'mixed purity': 'mixed' })[p] || 'none';
function nearestWord(pos) {
  let best = HT.WORDS[0], bd = 9;
  HT.WORDS.forEach(w => { const d = Math.hypot(w[1] - pos.x, w[2] - pos.y); if (d < bd) { bd = d; best = w; } });
  return best[0];
}

const rows = [];
let house = 1;
const seq = {};   // ids are a running number per kind: one page can appear twice in the transcription
function add(id, kind, source, toks, word, extra) {
  if (!toks.every(okTok)) return;   // a slot the photo could not read
  const colors = toks.map(t => HT.toHex(t)), n = colors.length;
  if (n < 2 || n > 9) return;
  const parts = HT.ROLE_PARTS[n], mainIdx = Math.max(0, parts.indexOf('main'));
  const R = HT.readPalette(colors), main = R.rs[mainIdx];
  const fams = [...new Set(R.rs.filter(r => !r.neutral).map(r => HT.TONES[r.ti].fam))];
  const mood = nearestWord(R.pos);
  seq[kind] = (seq[kind] || 0) + 1;
  rows.push(Object.assign({
    id: kind + '-' + seq[kind], src: id, kind, source,
    name: word ? cap(word) : HT.nameOf(colors[mainIdx]),
    word: word ? word.toLowerCase() : null,
    colors, parts, n,
    key_hue: main.neutral ? 'N' : HT.HUES[main.hi].k,
    fams,
    harmony: HT.harmonyOf(colors), tone_rel: toneRelKey(R.toneRel), purity: purityKey(R.purity),   // the client's own words
    mood, mood_x: +R.pos.x.toFixed(3), mood_y: +R.pos.y.toFixed(3),
    house: house++,
    metal: toks.some(t => HT.METAL[t]) || undefined,
  }, extra || {}));
}

// key-colour pages: a key page (pairs) and the page after it (triads, image triads)
const keys = [];
let chap = null;
BD.forEach(pg => {
  if (pg.key) { chap = { code: pg.key.code, tok: pg.key.rgb, i: keys.length }; keys.push(chap); }
  if (!chap) return;
  (pg.pairs || []).forEach((c, j) => add(`pair-${pg.page}-${j + 1}`, 'pair', 'reference', c, null));
  (pg.triads || []).forEach((t, j) => add(`triad-${pg.page}-${j + 1}`, 'triad', 'reference', t.c, t.image_en || null));
});
// base · secondary · accent (3–4 colours): base → main, sub → sub, accent → accent, accent2 → accent2
GD.forEach(pg => (pg.garments || []).forEach((g, j) => {
  if (g.flag) return;   // a value the photo got wrong
  const roles = ['base', 'sub', 'accent', 'accent2'].filter(r => r in g);
  if (roles.length < 3 || roles.some(r => !g[r])) return;
  const word = pg.section_jp ? (pg.section_en || '').split(',')[0].trim() : null;
  add(`bsa-${pg.page}-${j + 1}`, 'bsa', 'reference', roles.map(r => g[r]), word || null);
}));
// five colours in a space: wall → background, floor → ground, top → main, skirt → sub, V-neck → accent
SD.forEach(pg => (pg.scenes || []).forEach((sc, j) => {
  if (sc.flag) return;
  add(`five-${pg.page}-${j + 1}`, 'five', 'reference', ['wall', 'floor', 'top', 'skirt', 'accent'].map(k => sc[k]), sc.word_en || null);
}));
// six and seven colours, generated by the role rule: 7 per key colour and count (metallic keys left out)
const GEN_PER = 7;
keys.filter(k => !HT.METAL[k.tok.toLowerCase()] && !HT.METAL[k.tok]).forEach(k => {
  const keyHex = HT.toHex(k.tok);
  [6, 7].forEach(n => {
    for (let s = 1; s <= GEN_PER; s++) {
      const seed = (k.i + 1) * 1000 + n * 100 + s, items = HT.generateRoles(keyHex, n, seed);
      add(`gen-${k.code.replace(/[^A-Za-z0-9.]+/g, '').toLowerCase()}-${n}-${s}`, 'gen', 'organica', items.map(x => x.hex), null, { seed });
    }
  });
});

rows.forEach((r, i) => { r.position = i + 1; if (r.metal === undefined) delete r.metal; });

// ---- out ----
// rows.json keeps every facet (for a look at the numbers); the table keeps only the palette — TuneSutra reads the
// facets on the device from the colours (Organica.hueTone), so they follow the model.
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'rows.json'), JSON.stringify(rows));
const q = s => s == null ? 'null' : "'" + String(s).replace(/'/g, "''") + "'";
const arr = a => 'array[' + a.map(q).join(',') + ']::text[]';
// One jsonb literal. Row: [kind letter, word|'', colours 'rrggbb.rrggbb…']. SQL rebuilds the rest: id = kind-<n> (a running
// number per kind, in order), source from the kind, parts from n (ROLE_PARTS), position = house = the row's place.
const K1 = { pair: 'p', triad: 't', bsa: 'b', five: 'f', gen: 'g' };
if (rows.some((r, i) => r.house !== i + 1 || r.id !== r.kind + '-' + rows.slice(0, i + 1).filter(x => x.kind === r.kind).length)) throw new Error('ids / houses no longer follow the order');
const compact = rows.map(r => [K1[r.kind], r.word || '', r.colors.map(c => c.slice(1)).join('.')]);
const partsCase = 'case cardinality(colors) ' + Object.keys(HT.ROLE_PARTS).map(k => `when ${k} then ${arr(HT.ROLE_PARTS[k])}`).join(' ') + ' end';
fs.readdirSync(outDir).filter(f => /^(seed|insert)-.*\.sql$/.test(f)).forEach(f => fs.unlinkSync(path.join(outDir, f)));
// Three files (each small enough for one SQL call), split where a kind group ends so the per-kind numbering holds.
const GROUPS = [['pair', 'triad'], ['bsa'], ['five', 'gen']];
let off = 0;
GROUPS.forEach((kinds, g) => {
  const chunk = compact.filter((c, i) => kinds.indexOf(rows[i].kind) >= 0);
  if (rows.slice(off, off + chunk.length).some(r => kinds.indexOf(r.kind) < 0)) throw new Error('kind groups are not contiguous');
  fs.writeFileSync(path.join(outDir, `seed-${g + 1}.sql`), `with src as (select r, i from jsonb_array_elements(${q(JSON.stringify(chunk))}::jsonb) with ordinality as t(r, i)),
x as (select case r->>0 when 'p' then 'pair' when 't' then 'triad' when 'b' then 'bsa' when 'f' then 'five' else 'gen' end kind, nullif(r->>1, '') word,
  array(select '#' || c from unnest(string_to_array(r->>2, '.')) c) colors, (i + ${off})::int position from src),
y as (select x.*, kind || '-' || row_number() over (partition by kind order by position) id from x)
insert into public.palettes (id, kind, source, word, colors, parts, n, house, position)
select id, kind, case kind when 'gen' then 'organica' else 'reference' end, word, colors, ${partsCase}, cardinality(colors)::smallint, position, position from y
on conflict (id) do update set kind = excluded.kind, source = excluded.source, word = excluded.word, colors = excluded.colors, parts = excluded.parts,
  n = excluded.n, house = excluded.house, position = excluded.position, updated_at = now();
`);
  off += chunk.length;
});
const by = k => rows.reduce((a, r) => (a[r[k]] = (a[r[k]] || 0) + 1, a), {});
console.log(`${rows.length} palettes →`, outDir);
console.log('  kind  ', JSON.stringify(by('kind')));
console.log('  n     ', JSON.stringify(by('n')));
console.log('  mood  ', JSON.stringify(by('mood')));
console.log('  seed   seed-1..3.sql,', Math.round(JSON.stringify(compact).length / 1024), 'KB');
